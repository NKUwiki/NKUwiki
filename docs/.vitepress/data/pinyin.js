/**
 * 文本 → slug：汉字查表，字母数字保留，其余（标点、空格、全角符号）丢弃，音节用连字符连接。
 *
 * 「烤鸭饭」→ `kao-ya-fan`；生字 → `u70e4`（十六进制码位）。
 * 汉字用 \p{Script=Han} 判，不用 [\u4E00-\u9FA5]：扩展 B 区以后的字（如 𠮷）
 * 落在基本平面外，用区间判断会被当成标点直接丢掉，id 里就少了一个字。
 * onMissing 收集缺拼音的字，调用方可据此提示「这几个字建议手动改 id」。
 *
 * @param {string} text
 * @param {(char: string) => void} [onMissing]
 * @returns {string} 连字符分隔的 slug；文本里没有可用的汉字或字母数字时是空串
 */
export function slugify(text, onMissing) {
	const parts = []
	for (const char of String(text ?? '')) {
		if (/[a-z\d]/i.test(char)) {
			parts.push(char.toLowerCase())
			continue
		}
		const pinyin = PINYIN[char]
		if (pinyin) {
			parts.push(pinyin)
			continue
		}
		if (/\p{Script=Han}/u.test(char)) {
			onMissing?.(char)
			parts.push(`u${char.codePointAt(0).toString(16)}`)
		}
	}
	return parts.join('-')
}
